    // PLL_VIDEO : 50 MHz → 74.25 MHz (clk_pixel) + 371.25 MHz (clk_5x)
    // Replace with GOWIN IP instance generated by IP Core Generator
    // ------------------------------------------------------------------
    // Gowin_PLL_Video u_pll_video (
    //     .clkin   (clk),
    //     .clkout0 (clk_pixel),
    //     .clkout1 (clk_5x),
    //     .lock    (pll_video_lock)
