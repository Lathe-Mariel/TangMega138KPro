        .lock(pll_video_lock), //output lock
        .clkout0(clk_100), // 100MHz
        .clkout1(clk_5x), // 371.25MHz
        .clkin(clk) //input clkin
    );

    Gowin_CLKDIV your_instance_name(
        .clkout(clk_pixel), //output clkout
        .hclkin(clk_5x), //input hclkin
