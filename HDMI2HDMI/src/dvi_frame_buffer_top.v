module dvi_frame_buffer_top (
    //--------------------------------------------------------------------------
    // System Clock & Reset
    //--------------------------------------------------------------------------
    input  wire        clk,           // 50 MHz system clock (P16)
    input  wire        rst_n,         // Active-low reset (K16)

    //--------------------------------------------------------------------------
    // HDMI RX - TMDS Input (GOWIN DVI RX IP)
    //--------------------------------------------------------------------------
    input  wire        tmds_rx_clk_p,
    input  wire        tmds_rx_clk_n,
    input  wire [2:0]  tmds_rx_d_p,
    input  wire [2:0]  tmds_rx_d_n,

    //--------------------------------------------------------------------------
    // HDMI TX - TMDS Output (GOWIN DVI TX IP)
    //--------------------------------------------------------------------------
    output wire        O_tmds_clk_p,
    output wire [2:0]  O_tmds_data_p,

    //--------------------------------------------------------------------------
    // DDR3 SDRAM (GOWIN DDR Memory Interface IP)
    //--------------------------------------------------------------------------
    output wire [15:0] ddr_addr,
    output wire [2:0]  ddr_bank,
    output wire        ddr_cs,
    output wire        ddr_ras,
    output wire        ddr_cas,
    output wire        ddr_we,
    output wire        ddr_odt,
    output wire        ddr_cke,
    output wire        ddr_reset_n,
    output wire        ddr_ck,        // Differential (P=M2, N=L2)
    inout  wire [31:0] ddr_dq,
    inout  wire [3:0]  ddr_dqs,       // Differential (P,N pairs)
