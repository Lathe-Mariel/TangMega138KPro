//==============================================================================
// Top Module : dvi_frame_buffer_top.v
// Project    : DVI Frame Buffer with Image Composer
// Board      : Tang Mega 138K Pro Dock (GW5AST-LV138FPG676A)
// Updated    : 2026-04-04
//
// Block Diagram:
//
//  clk(50MHz) ──► PLL_SYS ──► clk_sys(100MHz)
//              └► PLL_VIDEO ─► clk_pixel(74.25MHz)
//                           └► clk_5x(371.25MHz)
//
//  HDMI_RX ──► DVI_RX_IP ──► rx_rgb/de/hs/vs  ──►  VFB_WRITE  ──► DDR3
//                │                                                 │
//            rx_pclk                                               │
//                                                              VFB_READ
//                                                                  │
//  HDMI_TX  ◄── DVI_TX_IP  ◄── IMAGE_COMPOSER  ◄───────────────────┘
//
// Screen Layout (1920x1080):
//   (  0,   0)-(1919,  49) : Orange border (top)
//   (  0,1030)-(1919,1079) : Orange border (bottom)
//   (  0,  50)-(  49,1029) : Orange border (left)
//   (1870,  50)-(1919,1029) : Orange border (right)
//   ( 50,  50)-(1500,1030) : Input video (scaled 1451x981)
//   (1500,  50)-(1549,1029) : Black spacer
//   (1550,  50)-(1870, 550) : Camera overlay reserved area
//   (1550, 550)-(1870, 929) : Black
//   (1550, 930)-(1870,1030) : "Lathe" text overlay
//==============================================================================

module dvi_frame_buffer_top (
    //--------------------------------------------------------------------------
    // System Clock & Reset
    //--------------------------------------------------------------------------
    input  wire        clk,           // 50 MHz system clock (P16)
    input  wire        rst_n,         // Active-low reset (K16)

    //--------------------------------------------------------------------------
    // HDMI RX - TMDS Input (GOWIN DVI RX IP)
    //--------------------------------------------------------------------------
    input  wire        tmds_rx_clk_p,
    input  wire        tmds_rx_clk_n,
    input  wire [2:0]  tmds_rx_d_p,
    input  wire [2:0]  tmds_rx_d_n,

    //--------------------------------------------------------------------------
    // HDMI TX - TMDS Output (GOWIN DVI TX IP)
    //--------------------------------------------------------------------------
    output wire        O_tmds_clk_p,
    output wire        O_tmds_clk_n,
    output wire [2:0]  O_tmds_data_p,
    output wire [2:0]  O_tmds_data_n,

    //--------------------------------------------------------------------------
    // DDR3 SDRAM (GOWIN DDR Memory Interface IP)
    //--------------------------------------------------------------------------
    output wire [15:0] ddr_addr,
    output wire [2:0]  ddr_bank,
    output wire        ddr_cs,
    output wire        ddr_ras,
    output wire        ddr_cas,
    output wire        ddr_we,
    output wire        ddr_odt,
    output wire        ddr_cke,
    output wire        ddr_reset_n,
    output wire        ddr_ck,        // Differential (P=M2, N=L2)
    output wire        ddr_ck_n,
    inout  wire [31:0] ddr_dq,
    inout  wire [3:0]  ddr_dqs,       // Differential (P,N pairs)
    inout  wire [3:0]  ddr_dqs_n,
    output wire [3:0]  ddr_dm,

    //--------------------------------------------------------------------------
    // CMOS Camera Interface (将来のオーバレイ用)
    //--------------------------------------------------------------------------
    input  wire        cmos_pclk,
    input  wire        cmos_href,
    input  wire        cmos_vsync,
    input  wire [7:0]  cmos_db,
    output wire        cmos_xclk,
    output wire        cmos_rst_n,
    output wire        cmos_pwdn,
    inout  wire        cmos_scl,
    inout  wire        cmos_sda,

    //--------------------------------------------------------------------------
    // Status LEDs / Switches / Fan
    //--------------------------------------------------------------------------
    output wire [5:0]  state_led,
    input  wire        sw0,
    input  wire        sw1,
    output wire        fan
);

//==============================================================================
// Internal Clocks & Reset
//==============================================================================

    wire clk_pixel;     // 74.25 MHz  - pixel clock
    wire clk_5x;        // 371.25 MHz - TMDS serializer clock
    wire clk_100;       // 100 MHz    - internal logic / AXI bus
    wire pll_video_lock;
    wire pll_sys_lock;

    wire sys_rst_n = rst_n & pll_video_lock & pll_sys_lock;  // synchronized reset

    // ------------------------------------------------------------------
    // PLL_VIDEO : 50 MHz → 74.25 MHz (clk_pixel) + 371.25 MHz (clk_5x)
    // Replace with GOWIN IP instance generated by IP Core Generator
    // ------------------------------------------------------------------
    // Gowin_PLL_Video u_pll_video (
    //     .clkin   (clk),
    //     .clkout0 (clk_pixel),
    //     .clkout1 (clk_5x),
    //     .lock    (pll_video_lock)
    // );

    Gowin_PLL_DVI pll_dvi(
        .lock(pll_video_lock), //output lock
        .clkout0(clk_5x), //output clkout0
        .clkin(clk), //input clkin
        .reset(reset) //input reset
    );

    Gowin_CLKDIV clkdiv_dvi(
        .clkout(clk_pixel), //output clkout
        .hclkin(clk_5x), //input hclkin
        .resetn(rst_n) //input resetn
    );

//    assign clk_pixel      = 1'b0;  // TODO: connect PLL output
//    assign clk_5x         = 1'b0;  // TODO: connect PLL output
//    assign pll_video_lock = 1'b0;  // TODO: connect PLL lock

    // ------------------------------------------------------------------
    // PLL_SYS : 50 MHz → 100 MHz (clk_sys)
    // ------------------------------------------------------------------
    // Gowin_PLL_Sys u_pll_sys (
    //     .clkin   (clk),
    //     .clkout0 (clk_sys),
    //     .lock    (pll_sys_lock)
    // );
//    assign clk_sys      = clk;    // TODO: connect PLL output
//    assign pll_sys_lock = 1'b1;   // TODO: connect PLL lock

    wire memory_clk;
    wire memory_pll_lock;

    Gowin_PLL pll_memory(
        .lock(memory_pll_lock), //output lock
        .clkout0(memory_clk), //output clkout0
        .clkout1(clk_100), //output clkout1
        .clkin(clk), //input clkin
        .reset(rst_n) //input reset
    );

//==============================================================================
// HDMI RX - DVI Receiver (GOWIN DVI RX IP)
//==============================================================================

    wire        rx_pclk;          // recovered pixel clock from TMDS
    wire [7:0]  rx_r, rx_g, rx_b;
    wire        rx_de;
    wire        rx_hsync;
    wire        rx_vsync;
    wire        rx_pll_lock;

    // ------------------------------------------------------------------
    // GOWIN DVI RX IP instance
    // ------------------------------------------------------------------
    // DVI_RX u_dvi_rx (
    //     .tmds_clk_p  (tmds_rx_clk_p),
    //     .tmds_clk_n  (tmds_rx_clk_n),
    //     .tmds_data_p (tmds_rx_d_p),
    //     .tmds_data_n (tmds_rx_d_n),
    //     .pclk        (rx_pclk),
    //     .de          (rx_de),
    //     .hsync       (rx_hsync),
    //     .vsync       (rx_vsync),
    //     .r           (rx_r),
    //     .g           (rx_g),
    //     .b           (rx_b),
    //     .pll_lock    (rx_pll_lock)
    // );

	DVI_RX_Top your_instance_name(
		.I_rst_n(rst_n), //input I_rst_n
		.I_tmds_clk_p(tmds_rx_clk_p), //input I_tmds_clk_p
		.I_tmds_clk_n(tmds_rx_clk_n), //input I_tmds_clk_n
		.I_tmds_data_p(tmds_rx_d_p), //input [2:0] I_tmds_data_p
		.I_tmds_data_n(tmds_rx_d_n), //input [2:0] I_tmds_data_n
		.O_tmds_clk(), //output O_tmds_clk
		.I_serial_clk(), //input I_serial_clk
		.O_rgb_clk(rx_pclk), //output O_rgb_clk
		.O_rgb_vs(rx_vsync), //output O_rgb_vs
		.O_rgb_hs(rx_hsync), //output O_rgb_hs
		.O_rgb_de(rx_de), //output O_rgb_de
		.O_rgb_r(rx_r), //output [7:0] O_rgb_r
		.O_rgb_g(rx_g), //output [7:0] O_rgb_g
		.O_rgb_b(rx_b) //output [7:0] O_rgb_b
	);

//    assign rx_pclk    = 1'b0;   // TODO: connect DVI RX IP
//    assign rx_r       = 8'h0;
//    assign rx_g       = 8'h0;
//    assign rx_b       = 8'h0;
//    assign rx_de      = 1'b0;
//    assign rx_hsync   = 1'b0;
//    assign rx_vsync   = 1'b0;
//    assign rx_pll_lock = 1'b0;

//==============================================================================
// Frame Buffer Write Path  (RX pixel clock domain → DDR3)
// GOWIN Video Frame Buffer IP (write port)
//==============================================================================

    wire        vfb_wr_ready;
    wire        vfb_frame_sync;   // indicates start of new frame (from RX vsync)

    // AXI4 Write Channel (to GOWIN DDR IP)
    wire [31:0] axi_waddr;
    wire [31:0] axi_wdata;
    wire [3:0]  axi_wstrb;
    wire        axi_wvalid;
    wire        axi_wready;

    // ------------------------------------------------------------------
    // GOWIN Video Frame Buffer (Write) IP instance
    // ------------------------------------------------------------------
    // VFB_Write u_vfb_wr (
    //     .pclk      (rx_pclk),
    //     .rst_n     (sys_rst_n),
    //     .de        (rx_de),
    //     .hsync     (rx_hsync),
    //     .vsync     (rx_vsync),
    //     .r         (rx_r),
    //     .g         (rx_g),
    //     .b         (rx_b),
    //     // AXI4 write master port ...
    // );

	Video_Frame_Buffer_Top your_instance_name(
		.I_rst_n(I_rst_n), //input I_rst_n
		.I_dma_clk(dma_clk), //input I_dma_clk < from DDR3 controller>

		.I_wr_halt(I_wr_halt), //input [0:0] I_wr_halt
		.I_rd_halt(I_rd_halt), //input [0:0] I_rd_halt
// video data input ( From DVI RX )
		.I_vin0_clk(I_vin0_clk), //input I_vin0_clk
		.I_vin0_vs_n(I_vin0_vs_n), //input I_vin0_vs_n
		.I_vin0_de(I_vin0_de), //input I_vin0_de
		.I_vin0_data(I_vin0_data), //input [15:0] I_vin0_data
		.O_vin0_fifo_full(), //output O_vin0_fifo_full
// video data output ( To Image Conposer - DVI TX )
		.I_vout0_clk(I_vout0_clk), //input I_vout0_clk
		.I_vout0_vs_n(I_vout0_vs_n), //input I_vout0_vs_n
		.I_vout0_de(I_vout0_de), //input I_vout0_de
		.O_vout0_den(O_vout0_den), //output O_vout0_den
		.O_vout0_data(O_vout0_data), //output [15:0] O_vout0_data

		.O_vout0_fifo_empty(), //output O_vout0_fifo_empty

		.I_cmd_ready(cmd_ready), //input I_cmd_ready <from DDR3 Controller>
		.O_cmd(cmd), //output [2:0] O_cmd < To DDR3 Controller>
		.O_cmd_en(cmd_en), //output O_cmd_en <To DDR3 Controller>
		.O_addr(addr), //output [28:0] O_addr
		.I_wr_data_rdy(wr_data_rdy), //input I_wr_data_rdy
		.O_wr_data_en(wr_data_en), //output O_wr_data_en
		.O_wr_data_end(wr_data_end), //output O_wr_data_end
		.O_wr_data(wr_data), //output [255:0] O_wr_data
		.O_wr_data_mask(wr_data_mask), //output [31:0] O_wr_data_mask
		.I_rd_data_valid(rd_data_valid), //input I_rd_data_valid
		.I_rd_data_end(rd_data_end), //input I_rd_data_end
		.I_rd_data(rd_data), //input [255:0] I_rd_data
		.I_init_calib_complete(init_calib_complete) //input I_init_calib_complete <from DDR3 controller>
	);

//==============================================================================
// DDR3 Memory Interface (GOWIN DDR Memory Interface IP - 400 MHz)
//==============================================================================

    // AXI4 Read Channel (to Image Composer)
    wire [31:0] axi_raddr;
    wire [31:0] axi_rdata;
    wire        axi_rvalid;
    wire        axi_rready;

    // ------------------------------------------------------------------
    // GOWIN DDR IP instance
    // ------------------------------------------------------------------
    // DDR3_Memory_Interface_Top u_ddr3 (
    //     .clk          (clk_100),          // reference clock 100MHz
    //     .memory_clk   (),             // 400 MHz from internal PLL
    //     .pll_stop     (1'b0),
    //     .rst_n        (sys_rst_n),
    //     // DDR3 physical pins
    //     .O_ddr_addr   (ddr_addr),
    //     .O_ddr_ba     (ddr_bank),
    //     .O_ddr_cs_n   (ddr_cs),
    //     .O_ddr_ras_n  (ddr_ras),
    //     .O_ddr_cas_n  (ddr_cas),
    //     .O_ddr_we_n   (ddr_we),
    //     .O_ddr_odt    (ddr_odt),
    //     .O_ddr_cke    (ddr_cke),
    //     .O_ddr_reset_n(ddr_reset_n),
    //     .IO_ddr_dq    (ddr_dq),
    //     .IO_ddr_dqs   (ddr_dqs),
    //     .O_ddr_dm     (ddr_dm),
    //     .O_ddr_clk    (ddr_ck),
    //     // AXI4 slave port ...
    // );

    wire dma_clk;
    wire init_calib_complete;
    wire cmd_ready;
    wire[2:0] cmd;
    wire cmd_en;
    wire[28:0] addr;
    wire wr_data_rdy;
    wire[255:0] wr_data;
    wire wr_data_en;
    wire wr_data_end;
    wire[31:0] wr_data_mask;
    wire[255:0] rd_data;
    wire rd_data_valid;
    wire rd_data_end;

	DDR3_Memory_Interface_Top your_instance_name(
		.clk(clk_100), //input clk
		.pll_stop(), //output pll_stop
		.memory_clk(memory_clk), //input memory_clk
		.pll_lock(memory_pll_lock), //input pll_lock
		.rst_n(rst_n), //input rst_n
		.clk_out(dma_clk), //output clk_out
		.ddr_rst(), //output ddr_rst

		.init_calib_complete(init_calib_complete), //output init_calib_complete
		.cmd_ready(cmd_ready), //output cmd_ready
		.cmd(cmd), //input [2:0] cmd
		.cmd_en(cmd_en), //input cmd_en
		.addr(addr), //input [28:0] addr
		.wr_data_rdy(wr_data_rdy), //output wr_data_rdy
		.wr_data(wr_data), //input [255:0] wr_data
		.wr_data_en(wr_data_en), //input wr_data_en
		.wr_data_end(wr_data_end), //input wr_data_end
		.wr_data_mask(wr_data_mask), //input [31:0] wr_data_mask
		.rd_data(rd_data), //output [255:0] rd_data
		.rd_data_valid(rd_data_valid), //output rd_data_valid
		.rd_data_end(rd_data_end), //output rd_data_end
		.sr_req(1'b0), //input sr_req
		.ref_req(1'b0), //input ref_req
		.sr_ack(), //output sr_ack
		.ref_ack(), //output ref_ack
		.burst(1'b1), //input burst
		.O_ddr_addr(ddr_addr), //output [14:0] O_ddr_addr
		.O_ddr_ba(ddr_bank), //output [2:0] O_ddr_ba
		.O_ddr_cs_n(ddr_cs), //output O_ddr_cs_n
		.O_ddr_ras_n(ddr_ras), //output O_ddr_ras_n
		.O_ddr_cas_n(ddr_cas), //output O_ddr_cas_n
		.O_ddr_we_n(ddr_we), //output O_ddr_we_n
		.O_ddr_clk(ddr_ck), //output O_ddr_clk
		.O_ddr_clk_n(ddr_ck_n), //output O_ddr_clk_n

		.O_ddr_cke(O_ddr_cke), //output O_ddr_cke
		.O_ddr_odt(O_ddr_odt), //output O_ddr_odt
		.O_ddr_reset_n(O_ddr_reset_n), //output O_ddr_reset_n
		.O_ddr_dqm(O_ddr_dqm), //output [3:0] O_ddr_dqm
		.IO_ddr_dq(IO_ddr_dq), //inout [31:0] IO_ddr_dq
		.IO_ddr_dqs(IO_ddr_dqs), //inout [3:0] IO_ddr_dqs
		.IO_ddr_dqs_n(IO_ddr_dqs_n) //inout [3:0] IO_ddr_dqs_n
	);


    // Tie off DDR3 pins until IP is connected
    assign ddr_addr    = 16'h0;
    assign ddr_bank    = 3'h0;
    assign ddr_cs      = 1'b1;   // deselect
    assign ddr_ras     = 1'b1;
    assign ddr_cas     = 1'b1;
    assign ddr_we      = 1'b1;
    assign ddr_odt     = 1'b0;
    assign ddr_cke     = 1'b0;
    assign ddr_reset_n = 1'b0;
    assign ddr_ck      = 1'b0;
    assign ddr_dm      = 4'h0;

//==============================================================================
// Frame Buffer Read Path  (DDR3 → clk_pixel domain)
// GOWIN Video Frame Buffer IP (read port)
//==============================================================================

    wire [7:0]  fb_r, fb_g, fb_b;   // scaled & read-out pixel from frame buffer
    wire        fb_de;

    // ------------------------------------------------------------------
    // GOWIN Video Frame Buffer (Read) IP instance
    // ------------------------------------------------------------------
    // VFB_Read u_vfb_rd (
    //     .pclk      (clk_pixel),
    //     .rst_n     (sys_rst_n),
    //     // AXI4 read master port ...
    //     .r         (fb_r),
    //     .g         (fb_g),
    //     .b         (fb_b),
    //     .de        (fb_de)
    // );
    assign fb_r  = 8'h0;   // TODO: connect VFB read IP
    assign fb_g  = 8'h0;
    assign fb_b  = 8'h0;
    assign fb_de = 1'b0;

//==============================================================================
// Image Composer
// Generates output video timing and composites all layers
//
// Layer priority (high → low):
//   1. "Lathe" text  (1550,930)-(1870,1030)
//   2. Orange border (50px all edges)
//   3. Input video   (50,50)-(1500,1030)  scaled 1451x981
//   4. Black background
//==============================================================================

    wire [7:0]  comp_r, comp_g, comp_b;
    wire        comp_de;
    wire        comp_hsync;
    wire        comp_vsync;

    image_composer u_composer (
        .clk_pixel  (clk_pixel),
        .rst_n      (sys_rst_n),
        // Frame buffer input (scaled input video)

        fb_rd_x,     // source X address (0~1919)
        fb_rd_y,     // source Y address (0~1079)
        fb_rd_en,    // read enable
        .fb_r       (fb_r),
        .fb_g       (fb_g),
        .fb_b       (fb_b),
        .fb_de      (fb_de),
        .fb_valid   (),
        // Composed output
        .out_r      (comp_r),
        .out_g      (comp_g),
        .out_b      (comp_b),
        .out_de     (comp_de),
        .out_hsync  (comp_hsync),
        .out_vsync  (comp_vsync)
    );

// fb_rd_x, fb_rd_y → フレームバッファの読み出しアドレス
// fb_rd_en         → 読み出しイネーブル
// fb_r/g/b         → フレームバッファからの返り値（2サイクル後）
// fb_valid         → フレームバッファデータ有効フラグ

//==============================================================================
// HDMI TX - DVI Transmitter (GOWIN DVI TX IP)
//==============================================================================

    // ------------------------------------------------------------------
    // GOWIN DVI TX IP instance
    // ------------------------------------------------------------------
    // DVI_TX u_dvi_tx (
    //     .pclk        (clk_pixel),
    //     .pclk_x5     (clk_5x),
    //     .rst_n       (sys_rst_n),
    //     .de          (comp_de),
    //     .hsync       (comp_hsync),
    //     .vsync       (comp_vsync),
    //     .r           (comp_r),
    //     .g           (comp_g),
    //     .b           (comp_b),
    //     .tmds_clk_p  (O_tmds_clk_p),
    //     .tmds_data_p (O_tmds_data_p)
    // );

	DVI_TX_Top your_instance_name(
		.I_rst_n(rst_n), //input I_rst_n
		.I_serial_clk(clk_5x), //input I_serial_clk
		.I_rgb_clk(clk_pixel), //input I_rgb_clk
		.I_rgb_vs(comp_vsync), //input I_rgb_vs
		.I_rgb_hs(comp_hsync), //input I_rgb_hs
		.I_rgb_de(comp_de),    //input I_rgb_de
		.I_rgb_r(comp_r),      //input [7:0] I_rgb_r
		.I_rgb_g(comp_g),      //input [7:0] I_rgb_g
		.I_rgb_b(comp_b),      //input [7:0] I_rgb_b
		.O_tmds_clk_p(O_tmds_clk_p), //output O_tmds_clk_p
		.O_tmds_clk_n(O_tmds_clk_n), //output O_tmds_clk_n
		.O_tmds_data_p(O_tmds_data_p), //output [2:0] O_tmds_data_p
		.O_tmds_data_n(O_tmds_data_n) //output [2:0] O_tmds_data_n
	);

//    assign O_tmds_clk_p   = 1'b0;   // TODO: connect DVI TX IP
//    assign O_tmds_data_p  = 3'h0;

//==============================================================================
// Camera Interface (将来のオーバレイ実装用 - 現在はスタブ)
//==============================================================================

    assign cmos_xclk  = clk_pixel;   // supply pixel clock to camera
    assign cmos_rst_n = sys_rst_n;
    assign cmos_pwdn  = 1'b0;        // power up camera

//==============================================================================
// Status LEDs  (sys_rst_n / pll lock / rx lock の状態を表示)
//==============================================================================

    assign state_led[0] = sys_rst_n;       // overall reset OK
    assign state_led[1] = pll_video_lock;  // video PLL locked
    assign state_led[2] = pll_sys_lock;    // sys PLL locked
    assign state_led[3] = rx_pll_lock;     // DVI RX PLL locked
    assign state_led[4] = rx_de;           // input video active
    assign state_led[5] = comp_de;         // output video active

//==============================================================================
// Fan Control (常時ON)
//==============================================================================

    assign fan = 1'b1;

endmodule

