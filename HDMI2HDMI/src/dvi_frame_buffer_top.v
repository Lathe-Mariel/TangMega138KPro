    //--------------------------------------------------------------------------
    // CMOS Camera Interface (将来のオーバレイ用)
    //--------------------------------------------------------------------------
    input  wire        cmos_pclk,
    input  wire        cmos_href,
    input  wire        cmos_vsync,
    input  wire [7:0]  cmos_db,
    output wire        cmos_xclk,
    output wire        cmos_rst_n,
    output wire        cmos_pwdn,
    inout  wire        cmos_scl,
    inout  wire        cmos_sda,

    //--------------------------------------------------------------------------
    // Status LEDs / Switches / Fan
    //--------------------------------------------------------------------------
    output wire [5:0]  state_led,
    input  wire        sw0,
    input  wire        sw1,
    output wire        fan
);

//==============================================================================
// Internal Clocks & Reset
//==============================================================================

    wire clk_pixel;     // 74.25 MHz  - pixel clock
    wire clk_5x;        // 371.25 MHz - TMDS serializer clock
    wire clk_100;       // 100 MHz    - internal logic / AXI bus
    wire pll_video_lock;
    wire pll_sys_lock;

