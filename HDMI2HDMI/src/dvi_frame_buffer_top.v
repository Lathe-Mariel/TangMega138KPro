module font_rom_lathe (
    input  wire        clk,
    input  wire [10:0] hcnt,
    input  wire [10:0] vcnt,
    input  wire [10:0] txt_x0,
    input  wire [10:0] txt_y0,
    output reg         pixel_on
);

    localparam FONT_H = 101;   // text area height
    localparam FONT_W = 321;   // text area width

    // Local pixel coordinates within text box
    wire [8:0] lx = hcnt - txt_x0;   // 0~320
    wire [6:0] ly = vcnt - txt_y0;   // 0~100

    wire in_box = (hcnt >= txt_x0) && (hcnt < txt_x0 + FONT_W) &&
                  (vcnt >= txt_y0) && (vcnt < txt_y0 + FONT_H);

    // Font ROM : 101 rows x 321 bits
    // Initialized via $readmemh from external .hex file
    // Each row is stored as 6 x 32-bit words (192 bits used, 321 needed → 11 words of 32bit)
    // TODO: generate lathe_font.hex with Python script (Step 4)
    reg [320:0] font_rom [0:FONT_H-1];

    initial begin
        // $readmemh("lathe_font.hex", font_rom);
